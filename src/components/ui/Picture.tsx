import Image from 'next/image';
import { images } from '@/config/images.generated';
import { imageAlt, type ImageSlug } from '@/config/images';

type Props = {
  slug: ImageSlug;
  sizes?: string;
  className?: string;
  imgClassName?: string;
  /** For the LCP image: eager + high fetch priority (no preload, so AVIF is not double-fetched). */
  eager?: boolean;
  alt?: string;
  /** Decorative images get empty alt. */
  decorative?: boolean;
  /** Art direction: a different photo below 768px (e.g. a portrait crop of the hero poster). */
  mobileSlug?: ImageSlug;
};

/**
 * Pre-optimised responsive photo: AVIF → WebP sources at 3 widths, blur placeholder,
 * intrinsic size reserved (no CLS). Files generated by `pnpm images`.
 */
export function Picture({
  slug,
  sizes = '100vw',
  className,
  imgClassName,
  eager,
  alt,
  decorative,
  mobileSlug,
}: Props) {
  const meta = images[slug];
  if (!meta) return null;
  const setFor = (sl: string, ext: string) =>
    (images[sl]?.widths ?? []).map((w) => `/images/${sl}-${w}.${ext} ${w}w`).join(', ');
  const set = (ext: string) => setFor(slug, ext);
  const mobile = mobileSlug && images[mobileSlug] ? mobileSlug : null;
  const fallback = meta.widths[Math.min(1, meta.widths.length - 1)];
  return (
    <picture className={className}>
      {mobile ? (
        <>
          <source
            media="(max-width: 767px)"
            type="image/avif"
            srcSet={setFor(mobile, 'avif')}
            sizes="100vw"
          />
          <source
            media="(max-width: 767px)"
            type="image/webp"
            srcSet={setFor(mobile, 'webp')}
            sizes="100vw"
          />
        </>
      ) : null}
      <source type="image/avif" srcSet={set('avif')} sizes={sizes} />
      <source type="image/webp" srcSet={set('webp')} sizes={sizes} />
      <Image
        src={`/images/${slug}-${fallback}.webp`}
        alt={decorative ? '' : (alt ?? imageAlt[slug])}
        width={meta.width}
        height={meta.height}
        sizes={sizes}
        placeholder="blur"
        blurDataURL={meta.blur}
        loading={eager ? 'eager' : 'lazy'}
        fetchPriority={eager ? 'high' : 'auto'}
        decoding="async"
        className={imgClassName}
      />
    </picture>
  );
}
