/**
 * Image pipeline: assets-src/images/*.(jpg|png) → public/images/<slug>-<w>.(avif|webp)
 * plus a typed manifest with intrinsic size and a tiny blur placeholder.
 *   pnpm images
 */
import { readdir, mkdir, writeFile } from 'node:fs/promises';
import path from 'node:path';
import sharp from 'sharp';

const SRC = 'assets-src/images';
const OUT = 'public/images';
const MANIFEST = 'src/config/images.generated.ts';
const WIDTHS = [640, 1280, 2048];

await mkdir(OUT, { recursive: true });
const files = (await readdir(SRC)).filter((f) => /\.(jpe?g|png)$/i.test(f)).sort();
const manifest = {};

for (const file of files) {
  const slug = file.replace(/\.(jpe?g|png)$/i, '');
  const input = sharp(path.join(SRC, file)).rotate();
  const { width, height } = await input.metadata();
  const widths = WIDTHS.filter((w) => w < width).concat(width > WIDTHS[2] ? [] : [width]);
  const sizes = [...new Set(widths.map((w) => Math.min(w, width)))].slice(0, 3);
  for (const w of sizes) {
    const base = input.clone().resize({ width: w, withoutEnlargement: true });
    await base
      .clone()
      .avif({ quality: 52, effort: 5 })
      .toFile(path.join(OUT, `${slug}-${w}.avif`));
    await base
      .clone()
      .webp({ quality: 74, effort: 5 })
      .toFile(path.join(OUT, `${slug}-${w}.webp`));
  }
  const blurBuf = await input.clone().resize(20).blur(1.2).webp({ quality: 40 }).toBuffer();
  manifest[slug] = {
    width,
    height,
    widths: sizes,
    blur: `data:image/webp;base64,${blurBuf.toString('base64')}`,
  };
  console.log(`✓ ${slug} (${width}×${height}) → ${sizes.join(', ')}`);
}

const body = `// AUTO-GENERATED by scripts/optimize-images.mjs — do not edit by hand.
export type ImageMeta = { width: number; height: number; widths: number[]; blur: string };
export const images: Record<string, ImageMeta> = ${JSON.stringify(manifest, null, 2)};
`;
await writeFile(MANIFEST, body);
console.log(`Wrote ${MANIFEST}`);
